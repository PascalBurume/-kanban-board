// Export and restore the teacher-created data that `npm run db:seed` destroys.
//
// seed.ts wipes every table and rebuilds the demo world from the book content. It
// never sets Lesson.authorId, so anything a teacher wrote in the Studio — library
// lessons, companions, their quizzes, custom exercises, the carnet — exists only
// in the database and does not come back. Re-seeding is routine here (every
// re-transcribed book needs it), so losing that work should not be the price.
//
//   node scripts/teacher-data-backup.mjs export [file]
//   node scripts/teacher-data-backup.mjs restore <file>
//
// Nothing is keyed by id: every id in this schema is a cuid regenerated by the
// seed. Rows are matched back by the identifiers that survive — a user's email, a
// module's (subjectSlug, order), a class's name, a book lesson's slug. A row whose
// anchor no longer exists (a chapter that moved, a class that was renamed) is
// reported and skipped rather than silently attached to the wrong place.

import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import { PrismaClient } from "@prisma/client";

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const prisma = new PrismaClient();

const mode = process.argv[2];
const argFile = process.argv[3];

// ---- stable anchors -------------------------------------------------------
// A module is identified by its book and position, a class by its name, a user
// by their email — all of which the seed reproduces verbatim.
const moduleKey = (m) => (m ? `${m.subjectSlug}#${m.order}` : null);

async function moduleIndex() {
  const mods = await prisma.module.findMany({ select: { id: true, subjectSlug: true, order: true } });
  return new Map(mods.map((m) => [moduleKey(m), m.id]));
}
async function classIndex() {
  const cs = await prisma.classGroup.findMany({ select: { id: true, name: true } });
  return new Map(cs.map((c) => [c.name, c.id]));
}
async function userIndex() {
  const us = await prisma.user.findMany({ where: { email: { not: null } }, select: { id: true, email: true } });
  return new Map(us.map((u) => [u.email, u.id]));
}
// Book lessons (authorId null) are recreated by the seed with the same slug.
async function bookLessonIndex() {
  const ls = await prisma.lesson.findMany({
    where: { authorId: null },
    select: { id: true, slug: true, module: { select: { subjectSlug: true, order: true } } },
  });
  return new Map(ls.map((l) => [`${moduleKey(l.module)}::${l.slug}`, l.id]));
}

async function exportAll(file) {
  const [mods, classes, books] = [await moduleIndex(), await classIndex(), await bookLessonIndex()];
  const modById = new Map([...mods].map(([k, v]) => [v, k]));
  const clsById = new Map([...classes].map(([k, v]) => [v, k]));
  const bookById = new Map([...books].map(([k, v]) => [v, k]));

  // Lesson.authorId is a bare column, not a relation, so the email is resolved
  // through the user index rather than an include.
  const emailById = new Map([...(await userIndex())].map(([email, id]) => [id, email]));
  const lessons = await prisma.lesson.findMany({
    where: { authorId: { not: null } },
    include: { quizzes: { include: { questions: { orderBy: { order: "asc" } } } } },
  });

  const exercises = await prisma.exercise.findMany({
    include: { author: { select: { email: true } }, links: true },
  });

  const plans = await prisma.modulePlan.findMany({ include: { teacher: { select: { email: true } } } });
  const projects = await prisma.notebookProject.findMany({ include: { teacher: { select: { email: true } } } });

  const data = {
    version: 1,
    exportedAt: new Date().toISOString(),
    lessons: lessons.map((l) => ({
      authorEmail: emailById.get(l.authorId) ?? null,
      moduleKey: l.moduleId ? modById.get(l.moduleId) ?? null : null,
      companionKey: l.companionOfId ? bookById.get(l.companionOfId) ?? null : null,
      slug: l.slug, title: l.title, order: l.order, status: l.status,
      contentMd: l.contentMd, estMinutes: l.estMinutes,
      sourceRef: l.sourceRef, subjectSlug: l.subjectSlug,
      quizzes: l.quizzes.map((q) => ({
        title: q.title,
        questions: q.questions.map((x) => ({
          type: x.type, promptMd: x.promptMd, optionsJson: x.optionsJson,
          answerJson: x.answerJson, explanationMd: x.explanationMd, order: x.order,
        })),
      })),
    })),
    exercises: exercises.map((e) => ({
      authorEmail: e.author?.email ?? null,
      subjectSlug: e.subjectSlug,
      className: e.classId ? clsById.get(e.classId) ?? null : null,
      title: e.title, statementMd: e.statementMd, solutionMd: e.solutionMd, status: e.status,
      links: e.links.map((k) => ({
        moduleKey: k.moduleId ? modById.get(k.moduleId) ?? null : null,
        // A link may point at a teacher lesson (restored below) or a book lesson.
        lessonSlug: null,
        bookLessonKey: k.lessonId ? bookById.get(k.lessonId) ?? null : null,
      })),
    })),
    modulePlans: plans.map((p) => ({
      teacherEmail: p.teacher?.email ?? null,
      className: clsById.get(p.classId) ?? null,
      moduleKey: modById.get(p.moduleId) ?? null,
      status: p.status, plannedFor: p.plannedFor, coveredAt: p.coveredAt,
      notesMd: p.notesMd, order: p.order,
    })),
    notebookProjects: projects.map((p) => ({
      teacherEmail: p.teacher?.email ?? null,
      className: clsById.get(p.classId) ?? null,
      subjectSlug: p.subjectSlug,
      moduleKey: p.moduleId ? modById.get(p.moduleId) ?? null : null,
      title: p.title, objectivesMd: p.objectivesMd, deliverableMd: p.deliverableMd,
      status: p.status, dueDate: p.dueDate,
    })),
    bookExerciseFixes: await prisma.bookExerciseFix.findMany(),
    // These cascade-delete with their lesson, so unlike a fix they DO die on a
    // reseed. Anchored by the lesson's (chapter, slug), which the seed reproduces.
    bookExerciseLinks: (await prisma.bookExerciseLink.findMany({
      select: {
        exId: true, createdById: true,
        lesson: { select: { slug: true, module: { select: { subjectSlug: true, order: true } } } },
      },
    })).map((l) => ({ exId: l.exId, lessonKey: `${moduleKey(l.lesson.module)}::${l.lesson.slug}` })),
  };

  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(data, null, 2));
  console.log(`\nteacher-data-backup — exported to ${path.relative(ROOT, file)}\n`);
  console.log(`  authored lessons  ${data.lessons.length}  (${data.lessons.reduce((a, l) => a + l.quizzes.length, 0)} quizzes)`);
  console.log(`  custom exercises  ${data.exercises.length}`);
  console.log(`  carnet plans      ${data.modulePlans.length}`);
  console.log(`  carnet projects   ${data.notebookProjects.length}`);
  console.log(`  book fixes        ${data.bookExerciseFixes.length}`);
  console.log(`  book ex. links    ${data.bookExerciseLinks.length}\n`);
  const orphan = data.lessons.filter((l) => !l.authorEmail).length;
  if (orphan) console.log(`  ! ${orphan} lesson(s) have no author email and cannot be restored\n`);
}

async function restoreAll(file) {
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  const [mods, classes, users, books] = [await moduleIndex(), await classIndex(), await userIndex(), await bookLessonIndex()];
  const skipped = [];
  let lessonsIn = 0, quizzesIn = 0, exIn = 0, planIn = 0, projIn = 0, fixIn = 0;

  for (const l of data.lessons) {
    const authorId = users.get(l.authorEmail);
    if (!authorId) { skipped.push(`lesson "${l.title}" — no user ${l.authorEmail}`); continue; }
    const moduleId = l.moduleKey ? mods.get(l.moduleKey) ?? null : null;
    if (l.moduleKey && !moduleId) { skipped.push(`lesson "${l.title}" — chapter ${l.moduleKey} is gone`); continue; }
    const companionOfId = l.companionKey ? books.get(l.companionKey) ?? null : null;
    if (l.companionKey && !companionOfId) skipped.push(`lesson "${l.title}" — companion target gone, restored unattached`);

    // Restore is re-runnable: a second pass after a partial failure must not
    // leave the teacher with two copies of every lesson.
    const dupe = await prisma.lesson.findFirst({ where: { authorId, slug: l.slug, title: l.title }, select: { id: true } });
    if (dupe) { skipped.push(`lesson "${l.title}" — already restored`); continue; }

    const created = await prisma.lesson.create({
      data: {
        moduleId, companionOfId, authorId,
        slug: l.slug, title: l.title, order: l.order, status: l.status,
        contentMd: l.contentMd, estMinutes: l.estMinutes,
        sourceRef: l.sourceRef, subjectSlug: l.subjectSlug,
      },
    });
    lessonsIn++;
    for (const q of l.quizzes) {
      await prisma.quiz.create({
        data: {
          lessonId: created.id, title: q.title,
          questions: { create: q.questions },
        },
      });
      quizzesIn++;
    }
  }

  for (const e of data.exercises) {
    const authorId = users.get(e.authorEmail);
    if (!authorId) { skipped.push(`exercise "${e.title}" — no user ${e.authorEmail}`); continue; }
    const subject = await prisma.subject.findUnique({ where: { slug: e.subjectSlug }, select: { slug: true } });
    if (!subject) { skipped.push(`exercise "${e.title}" — subject ${e.subjectSlug} is gone`); continue; }
    const dupe = await prisma.exercise.findFirst({ where: { authorId, statementMd: e.statementMd }, select: { id: true } });
    if (dupe) { skipped.push(`exercise "${e.title}" — already restored`); continue; }
    const created = await prisma.exercise.create({
      data: {
        authorId, subjectSlug: e.subjectSlug,
        classId: e.className ? classes.get(e.className) ?? null : null,
        title: e.title, statementMd: e.statementMd, solutionMd: e.solutionMd, status: e.status,
      },
    });
    exIn++;
    for (const k of e.links) {
      const moduleId = k.moduleKey ? mods.get(k.moduleKey) ?? null : null;
      const lessonId = k.bookLessonKey ? books.get(k.bookLessonKey) ?? null : null;
      if (!moduleId && !lessonId) continue;
      await prisma.exerciseLink.create({ data: { exerciseId: created.id, moduleId, lessonId } });
    }
  }

  // The carnet IS seeded (seed.ts writes 54 plans and 9 projects), so these rows
  // already exist after a reseed. Upsert rather than create: the backup carries
  // the teacher's own status and notes, which should win over the seeded default,
  // and a plain create would trip the (teacher, class, module) unique constraint.
  for (const p of data.modulePlans) {
    const teacherId = users.get(p.teacherEmail), classId = classes.get(p.className), moduleId = mods.get(p.moduleKey);
    if (!teacherId || !classId || !moduleId) { skipped.push(`carnet plan ${p.moduleKey} — anchor missing`); continue; }
    const fields = {
      status: p.status, plannedFor: p.plannedFor, coveredAt: p.coveredAt,
      notesMd: p.notesMd, order: p.order,
    };
    await prisma.modulePlan.upsert({
      where: { teacherId_classId_moduleId: { teacherId, classId, moduleId } },
      update: fields,
      create: { teacherId, classId, moduleId, ...fields },
    });
    planIn++;
  }

  for (const p of data.notebookProjects) {
    const teacherId = users.get(p.teacherEmail), classId = classes.get(p.className);
    if (!teacherId || !classId) { skipped.push(`carnet project "${p.title}" — anchor missing`); continue; }
    // No unique key here, so identity is (teacher, class, title) — enough to keep
    // a re-run from stacking duplicates of the same project.
    const exists = await prisma.notebookProject.findFirst({ where: { teacherId, classId, title: p.title }, select: { id: true } });
    if (exists) { skipped.push(`carnet project "${p.title}" — already present`); continue; }
    await prisma.notebookProject.create({
      data: {
        teacherId, classId, subjectSlug: p.subjectSlug,
        moduleId: p.moduleKey ? mods.get(p.moduleKey) ?? null : null,
        title: p.title, objectivesMd: p.objectivesMd, deliverableMd: p.deliverableMd,
        status: p.status, dueDate: p.dueDate,
      },
    });
    projIn++;
  }

  // BookExerciseFix keys on a plain exercise number, not a relation, so the seed
  // leaves it alone — restore only what is actually missing.
  for (const f of data.bookExerciseFixes ?? []) {
    const exists = await prisma.bookExerciseFix.findFirst({ where: { exId: f.exId } });
    if (exists) continue;
    const { id, ...rest } = f;
    await prisma.bookExerciseFix.create({ data: rest });
    fixIn++;
  }

  let linkIn = 0;
  for (const l of data.bookExerciseLinks ?? []) {
    const lessonId = books.get(l.lessonKey);
    if (!lessonId) { skipped.push(`book link ex ${l.exId} — lesson ${l.lessonKey} is gone`); continue; }
    await prisma.bookExerciseLink.upsert({
      where: { exId_lessonId: { exId: l.exId, lessonId } },
      update: {},
      create: { exId: l.exId, lessonId },
    });
    linkIn++;
  }

  console.log(`\nteacher-data-backup — restored from ${path.relative(ROOT, file)}\n`);
  console.log(`  book ex. links    ${linkIn}/${(data.bookExerciseLinks ?? []).length}`);
  console.log(`  authored lessons  ${lessonsIn}/${data.lessons.length}  (${quizzesIn} quizzes)`);
  console.log(`  custom exercises  ${exIn}/${data.exercises.length}`);
  console.log(`  carnet plans      ${planIn}/${data.modulePlans.length}`);
  console.log(`  carnet projects   ${projIn}/${data.notebookProjects.length}`);
  console.log(`  book fixes        ${fixIn} added`);
  if (skipped.length) {
    console.log(`\n  ${skipped.length} skipped:`);
    for (const s of skipped) console.log(`    - ${s}`);
  }
  console.log();
}

const file = argFile
  ? path.resolve(ROOT, argFile)
  : path.join(ROOT, "content/backups/teacher-data.json");

if (mode === "export") await exportAll(file);
else if (mode === "restore") await restoreAll(file);
else {
  console.error("usage: teacher-data-backup.mjs export|restore [file]");
  process.exitCode = 1;
}
await prisma.$disconnect();
